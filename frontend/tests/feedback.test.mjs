import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const temporary = await mkdtemp(path.join(process.cwd(), 'tests/.feedback-'));
try {
  const outfile = path.join(temporary, 'bundle.mjs');
  await build({ stdin: { contents: `export * from './src/services/feedbackService'; export {selectRevision} from './src/components/ai/RevisionInstructions'; export {generateOwnerImages} from './src/services/ownerAiService'; export {default as api} from './src/services/api'; export {CommentHistory, default as ImageComments} from './src/components/ai/ImageComments';`, resolveDir: process.cwd() }, bundle: true, format: 'esm', platform: 'node', packages: 'external', loader: { '.css': 'empty' }, jsx: 'automatic', outfile, define: { 'import.meta.env': '{}' } });
  const m = await import(pathToFileURL(outfile));
  const calls = [];
  m.api.defaults.adapter = async config => { calls.push(config); return { data: [], status: 200, headers: {}, config }; };
  const signal = new AbortController().signal;
  await m.getComments('safe/token', 2, signal);
  const data = { comment: 'Brighter', request_key: 'same-retry-key' };
  await m.addComment('safe/token', 2, data); await m.addComment('safe/token', 2, data);
  await m.getFeedback(4, signal); await m.updateFeedback(4, 7, {status: 'resolved', revised_asset_id: 9});
  assert.deepEqual(calls.map(c => [c.method, c.url]), [['get','/sharing/safe%2Ftoken/images/2/comments'],['post','/sharing/safe%2Ftoken/images/2/comments'],['post','/sharing/safe%2Ftoken/images/2/comments'],['get','/owner/projects/4/feedback'],['patch','/owner/projects/4/feedback/7']]);
  assert.equal(calls[0].signal, signal); assert.equal(calls[1].data, calls[2].data);
  const html = renderToStaticMarkup(React.createElement(m.CommentHistory, {comments: [{id: 1, comment: '<script>alert(1)</script>', status:'in_progress', created_at:'2026-11-10T00:00:00Z'}]}));
  assert.match(html, /&lt;script&gt;/); assert.doesNotMatch(html, /<script>/); assert.match(html, /in progress/);
  assert.match(renderToStaticMarkup(React.createElement(m.ImageComments,{token:'test',imageId:2})), /Add Comment/);
  assert.match(m.feedbackError({response:{status:503}}), /not available yet/);
  const feedback = {id:7,project_id:4,plan_id:8,comment:'Brighten the background'};
  assert.equal(m.selectRevision([feedback],4,8,7),feedback);
  assert.equal(m.selectRevision([feedback],5,8,7),undefined);
  assert.equal(m.selectRevision([feedback],4,9,7),undefined);
  await m.generateOwnerImages({planId:8,projectId:4,description:feedback.comment,idempotencyKey:'revision-key'});
  const generation = calls.at(-1);
  assert.equal(generation.url, '/owner/projects/4/ai/generations');
  assert.equal(generation.data.get('description'), feedback.comment);
  assert.equal(generation.data.get('plan_id'), '8');
  const revisionLink = await readFile('src/components/projects/ProjectFeedback.jsx','utf8');
  assert.match(revisionLink, /&feedback=\$\{row.id\}/);
  const generator = await readFile('src/pages/owner/AIGenerator.jsx','utf8');
  assert.match(generator, /disabled=\{retrying \|\| busy\}/);
  assert.match(generator, /setDescription\(text\)/);
  const gallery = await readFile('src/pages/shared/SharedGallery.jsx','utf8');
  const card = await readFile('src/components/ai/GeneratedImageCard.jsx','utf8');
  assert.match(gallery, /allowDownload=\{false\}/); assert.match(card, /allowDownload = true/); assert.match(card, /url && allowDownload &&/);
} finally { await rm(temporary, {recursive:true,force:true}); }
